package com.anpfuel.domain.map

import kotlin.math.abs
import kotlin.math.max
import kotlin.math.min
import kotlin.math.sqrt

/** A WGS84 point in degrees. */
data class MapRegionPoint(val latitude: Double, val longitude: Double) {
    val valid: Boolean
        get() = latitude.isFinite() && longitude.isFinite() && latitude in -90.0..90.0 && longitude in -180.0..180.0
}

/**
 * The 23 Brazil leaf country ids of the pinned CoMaps engine
 * (`data/borders/Brazil_*.poly`). The native file of a region must be named
 * exactly `<countryId>.mwm`, spaces included, or the engine treats it as a
 * "fake country" (rendered, but invisible to storage and routing).
 */
object MapRegionCatalog {
    private val namesPtBr: Map<String, String> = linkedMapOf(
        "Brazil_Bahia" to "Bahia",
        "Brazil_Goias_Brasilia" to "Goiás – Sul e Distrito Federal",
        "Brazil_Goias_North" to "Goiás – Norte",
        "Brazil_Mato Grosso Do Sul" to "Mato Grosso do Sul",
        "Brazil_Mato Grosso" to "Mato Grosso",
        "Brazil_Northeast Region_East" to "Nordeste – Leste",
        "Brazil_Northeast Region_West" to "Nordeste – Oeste",
        "Brazil_North Region_East" to "Norte – Leste",
        "Brazil_North Region_West" to "Norte – Oeste",
        "Brazil_Paraiba" to "Paraíba",
        "Brazil_Parana_East" to "Paraná – Leste",
        "Brazil_Parana_West" to "Paraná – Oeste",
        "Brazil_Rio Grande do Norte" to "Rio Grande do Norte",
        "Brazil_Santa Catarina" to "Santa Catarina",
        "Brazil_Southeast Region_Espirito Santo" to "Espírito Santo",
        "Brazil_Southeast Region_Minas Gerais_Contagem" to "Minas Gerais – Centro-Sul",
        "Brazil_Southeast Region_Minas Gerais_North" to "Minas Gerais – Norte, Leste e Triângulo",
        "Brazil_Southeast Region_Rio de Janeiro" to "Rio de Janeiro",
        "Brazil_Southeast Region_Sao Paulo_Campinas" to "São Paulo – Campinas",
        "Brazil_Southeast Region_Sao Paulo_City" to "São Paulo (capital e litoral)",
        "Brazil_Southeast Region_Sao Paulo_West" to "São Paulo – Oeste",
        "Brazil_South Region_East" to "Rio Grande do Sul – Leste",
        "Brazil_South Region_West" to "Rio Grande do Sul – Oeste",
    )

    private val slugPattern = Regex("^[a-z0-9-]{1,64}$")
    private val separators = Regex("[ _]+")

    val countryIds: Set<String> get() = namesPtBr.keys

    /**
     * Distribution slug of a CoMaps Brazil leaf id: `brazil-` + the part after
     * `Brazil_`, lowercased, each run of spaces/underscores replaced by `-`
     * (`Brazil_Mato Grosso` -> `brazil-mato-grosso`).
     */
    fun slugOf(countryId: String): String {
        if (!countryId.startsWith("Brazil_")) throw MapContractException("invalid-region")
        val tail = countryId.removePrefix("Brazil_").lowercase().replace(separators, "-")
        val slug = "brazil-$tail"
        if (!slugPattern.matches(slug)) throw MapContractException("invalid-region")
        return slug
    }

    fun countryIdForSlug(slug: String): String? = namesPtBr.keys.firstOrNull { slugOf(it) == slug }

    /** Human-readable pt-BR region name (proper names stay in Portuguese). */
    fun displayName(countryId: String): String = namesPtBr[countryId] ?: countryId

    /** Native file name the engine registers for this country id. */
    fun nativeFileName(countryId: String): String = "$countryId.mwm"
}

/**
 * Picks the coordinate that represents the city the user opened on the map:
 * the camera center the map itself moved to for that city, else the centroid
 * of the city's loaded stations, else the built-in city coordinate. Invalid
 * points are skipped. Returns null when nothing is known.
 */
fun chooseCityRegionPoint(
    cityCameraCenter: MapRegionPoint?,
    cityStations: List<MapRegionPoint>,
    builtInCity: MapRegionPoint?,
): MapRegionPoint? {
    cityCameraCenter?.takeIf { it.valid }?.let { return it }
    val stations = cityStations.filter { it.valid }
    if (stations.isNotEmpty()) {
        return MapRegionPoint(stations.sumOf { it.latitude } / stations.size, stations.sumOf { it.longitude } / stations.size)
    }
    return builtInCity?.takeIf { it.valid }
}

/**
 * Point-in-region lookup over simplified CoMaps Brazil borders (asset format
 * `abastevo.map-regions-v1`, generated by `scripts/maps/generate-map-regions.py`).
 * Each region is tested with the even-odd rule over all its rings, so holes
 * and multipolygons are exact. Douglas-Peucker simplification can open small
 * slivers between neighbours: a point inside no region but within
 * [edgeToleranceDeg] of a border falls back to the nearest region.
 */
class MapRegionIndex private constructor(
    private val regions: List<Region>,
    private val edgeToleranceDeg: Double,
) {
    private class Ring(val xs: DoubleArray, val ys: DoubleArray) {
        val minX = xs.min()
        val maxX = xs.max()
        val minY = ys.min()
        val maxY = ys.max()

        fun crossings(x: Double, y: Double): Boolean {
            if (x < minX || x > maxX || y < minY || y > maxY) return false
            var inside = false
            var j = xs.size - 1
            for (i in xs.indices) {
                if ((ys[i] > y) != (ys[j] > y) &&
                    x < (xs[j] - xs[i]) * (y - ys[i]) / (ys[j] - ys[i]) + xs[i]
                ) {
                    inside = !inside
                }
                j = i
            }
            return inside
        }

        fun distance(x: Double, y: Double): Double {
            var best = Double.MAX_VALUE
            var j = xs.size - 1
            for (i in xs.indices) {
                best = min(best, segmentDistance(x, y, xs[j], ys[j], xs[i], ys[i]))
                j = i
            }
            return best
        }
    }

    private class Region(val countryId: String, val rings: List<Ring>) {
        val minX = rings.minOf { it.minX }
        val maxX = rings.maxOf { it.maxX }
        val minY = rings.minOf { it.minY }
        val maxY = rings.maxOf { it.maxY }

        fun contains(x: Double, y: Double): Boolean {
            if (x < minX || x > maxX || y < minY || y > maxY) return false
            var inside = false
            for (ring in rings) if (ring.crossings(x, y)) inside = !inside
            return inside
        }

        fun distance(x: Double, y: Double, limit: Double): Double {
            if (x < minX - limit || x > maxX + limit || y < minY - limit || y > maxY + limit) return Double.MAX_VALUE
            return rings.minOf { it.distance(x, y) }
        }
    }

    val countryIds: List<String> get() = regions.map { it.countryId }

    /** CoMaps country id containing the point, or null outside every region. */
    fun regionFor(latitude: Double, longitude: Double): String? {
        if (!MapRegionPoint(latitude, longitude).valid) return null
        regions.firstOrNull { it.contains(longitude, latitude) }?.let { return it.countryId }
        var best: Region? = null
        var bestDistance = edgeToleranceDeg
        for (region in regions) {
            val distance = region.distance(longitude, latitude, edgeToleranceDeg)
            if (distance <= bestDistance) {
                best = region
                bestDistance = distance
            }
        }
        return best?.countryId
    }

    companion object {
        const val FORMAT = "abastevo.map-regions-v1"
        private const val SCALE = 10_000.0
        private const val MAX_REGIONS = 64
        private const val MAX_VERTICES = 200_000

        fun parse(text: String, edgeToleranceDeg: Double = 0.02): MapRegionIndex {
            val lines = text.lineSequence().map { it.trimEnd('\r') }.filter { it.isNotEmpty() }.toList()
            if (lines.firstOrNull() != FORMAT) throw MapContractException("unsupported-region-index")
            val regions = mutableListOf<Region>()
            var currentId: String? = null
            var currentRings = mutableListOf<Ring>()
            var vertices = 0
            fun flush() {
                val id = currentId ?: return
                if (currentRings.isEmpty()) throw MapContractException("region-without-rings")
                regions += Region(id, currentRings)
            }
            for (line in lines.drop(1)) {
                if (line.startsWith("#")) continue
                val tab = line.indexOf('\t')
                if (tab != 1) throw MapContractException("malformed-region-index")
                val value = line.substring(2)
                when (line[0]) {
                    'R' -> {
                        flush()
                        if (!value.startsWith("Brazil_") || regions.any { it.countryId == value }) {
                            throw MapContractException("invalid-region")
                        }
                        currentId = value
                        currentRings = mutableListOf()
                    }
                    'O', 'H' -> {
                        if (currentId == null) throw MapContractException("malformed-region-index")
                        val ring = decodeRing(value)
                        vertices += ring.xs.size
                        if (vertices > MAX_VERTICES) throw MapContractException("region-index-too-large")
                        currentRings += ring
                    }
                    else -> throw MapContractException("malformed-region-index")
                }
            }
            flush()
            if (regions.isEmpty() || regions.size > MAX_REGIONS) throw MapContractException("region-count")
            return MapRegionIndex(regions, edgeToleranceDeg)
        }

        private fun decodeRing(encoded: String): Ring {
            val pairs = encoded.split(';')
            if (pairs.size < 3) throw MapContractException("malformed-region-ring")
            val xs = DoubleArray(pairs.size)
            val ys = DoubleArray(pairs.size)
            var x = 0L
            var y = 0L
            for ((i, pair) in pairs.withIndex()) {
                val comma = pair.indexOf(',')
                if (comma <= 0) throw MapContractException("malformed-region-ring")
                val dx = pair.substring(0, comma).toLongOrNull() ?: throw MapContractException("malformed-region-ring")
                val dy = pair.substring(comma + 1).toLongOrNull() ?: throw MapContractException("malformed-region-ring")
                x += dx
                y += dy
                xs[i] = x / SCALE
                ys[i] = y / SCALE
                if (abs(xs[i]) > 180.0 || abs(ys[i]) > 90.0) throw MapContractException("malformed-region-ring")
            }
            return Ring(xs, ys)
        }

        private fun segmentDistance(px: Double, py: Double, ax: Double, ay: Double, bx: Double, by: Double): Double {
            val dx = bx - ax
            val dy = by - ay
            val lengthSquared = dx * dx + dy * dy
            val t = if (lengthSquared == 0.0) 0.0 else max(0.0, min(1.0, ((px - ax) * dx + (py - ay) * dy) / lengthSquared))
            val cx = ax + t * dx - px
            val cy = ay + t * dy - py
            return sqrt(cx * cx + cy * cy)
        }
    }
}
