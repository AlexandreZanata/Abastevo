package runtimegrants

import (
	"bytes"
	"errors"
	"fmt"
	"regexp"
	"strings"
)

// ScriptPath is the repository path of the rendered script.
const ScriptPath = "infra/db/runtime-role.sql"

// RoleVariable is the psql variable naming the runtime role.
const RoleVariable = "runtime_role"

var roleName = regexp.MustCompile(`^[a-z_][a-z0-9_]{0,62}$`)

// ErrInvalidRole refuses role names outside the reviewed lower-case form.
var ErrInvalidRole = errors.New("runtimegrants: invalid runtime role name")

// Render produces the deterministic provisioning script for inv. The script
// is applied by the migration owner with psql; it creates or converges the
// role, never sets or prints a password, grants exactly the inventory and
// verifies the result inside one transaction.
func Render(inv Inventory) []byte {
	var b bytes.Buffer
	granted, none := 0, 0
	for _, t := range inv.Tables {
		if len(t.Privileges) == 0 {
			none++
		} else {
			granted++
		}
	}
	allowedDefiner := []string{}
	fmt.Fprintf(&b, `-- GENERATED by backend/internal/platform/runtimegrants; do not edit by hand.
-- Ordinary runtime login of the composed API and worker (EMP-REL-002,
-- B-BR-EMP-556..558, EDR-363..365). Regenerate from backend/ after any
-- migration or SQL change:
--   ANPFUEL_RUNTIME_GRANTS_WRITE=1 go test -tags=integration -count=1 \
--     -run TestRuntimeScriptMatchesHead ./internal/platform/runtimegrants
-- Apply as the migration owner, on exactly the schema version below:
--   psql "<owner DSN>" -v ON_ERROR_STOP=1 -v %[1]s=abastevo_runtime -f %[2]s
-- The script never sets, stores or prints a password: the operator sets it
-- from a secret afterwards. It is idempotent and converges the role to this
-- inventory; it refuses another schema version, an owner or privileged role
-- and any TRUNCATE, DDL or SECURITY DEFINER access.
-- Schema version: %[3]s. Relations: %[4]d granted, %[5]d without access.
-- Sequences: %[6]d. Explicit functions: %[7]d.

BEGIN;
SELECT pg_catalog.set_config('abastevo.runtime_role', :'%[1]s', true);

DO $runtime_role$
DECLARE
  role_name text := pg_catalog.current_setting('abastevo.runtime_role');
  role_oid oid;
  head text;
BEGIN
  IF role_name !~ '^[a-z_][a-z0-9_]{0,62}$' THEN
    RAISE EXCEPTION 'runtime role name must match ^[a-z_][a-z0-9_]{0,62}$';
  END IF;
  IF role_name = current_user OR role_name = session_user THEN
    RAISE EXCEPTION 'the runtime role cannot be the migration owner';
  END IF;
  SELECT max(version) INTO head FROM public.schema_migrations;
  IF head IS DISTINCT FROM '%[3]s' THEN
    RAISE EXCEPTION 'runtime grant inventory is for schema %[3]s but the database is at %%: apply the script of the deployed release', head;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_catalog.pg_roles WHERE rolname = role_name) THEN
    EXECUTE pg_catalog.format('CREATE ROLE %%I', role_name);
  END IF;
  EXECUTE pg_catalog.format('ALTER ROLE %%I WITH LOGIN NOSUPERUSER NOBYPASSRLS NOCREATEDB NOCREATEROLE NOINHERIT NOREPLICATION', role_name);
  SELECT oid INTO role_oid FROM pg_catalog.pg_roles WHERE rolname = role_name;
  IF EXISTS (SELECT 1 FROM pg_catalog.pg_auth_members WHERE member = role_oid) THEN
    RAISE EXCEPTION 'the runtime role must be a member of no role';
  END IF;
  IF EXISTS (SELECT 1 FROM pg_catalog.pg_class WHERE relowner = role_oid)
     OR EXISTS (SELECT 1 FROM pg_catalog.pg_proc WHERE proowner = role_oid)
     OR EXISTS (SELECT 1 FROM pg_catalog.pg_type WHERE typowner = role_oid)
     OR EXISTS (SELECT 1 FROM pg_catalog.pg_namespace WHERE nspowner = role_oid)
     OR EXISTS (SELECT 1 FROM pg_catalog.pg_database WHERE datdba = role_oid) THEN
    RAISE EXCEPTION 'the runtime role must own nothing';
  END IF;
  EXECUTE pg_catalog.format('REVOKE ALL ON ALL TABLES IN SCHEMA public FROM %%I', role_name);
  EXECUTE pg_catalog.format('REVOKE ALL ON ALL SEQUENCES IN SCHEMA public FROM %%I', role_name);
  EXECUTE pg_catalog.format('REVOKE ALL ON ALL ROUTINES IN SCHEMA public FROM %%I', role_name);
  EXECUTE pg_catalog.format('REVOKE ALL ON SCHEMA public FROM %%I', role_name);
  EXECUTE pg_catalog.format('REVOKE ALL ON DATABASE %%I FROM %%I', pg_catalog.current_database(), role_name);
  EXECUTE pg_catalog.format('ALTER DEFAULT PRIVILEGES IN SCHEMA public REVOKE ALL ON TABLES FROM %%I', role_name);
  EXECUTE pg_catalog.format('ALTER DEFAULT PRIVILEGES IN SCHEMA public REVOKE ALL ON SEQUENCES FROM %%I', role_name);
  EXECUTE pg_catalog.format('GRANT CONNECT, TEMPORARY ON DATABASE %%I TO %%I', pg_catalog.current_database(), role_name);
END
$runtime_role$;

GRANT USAGE ON SCHEMA public TO :"%[1]s";

`, RoleVariable, ScriptPath, inv.SchemaVersion, granted, none, len(inv.Sequences), len(inv.Functions))
	if len(inv.Limits) > 0 {
		b.WriteString("-- Reviewed limits (EDR-363):\n")
		for _, l := range inv.Limits {
			fmt.Fprintf(&b, "--   %s at most %s: %s.\n", l.Table, strings.Join(l.Allowed, ", "), l.Reason)
		}
	}
	if len(inv.OperatorOnly) > 0 {
		b.WriteString("-- Operator-only functions referenced by the binaries, never granted here:\n")
		for _, o := range inv.OperatorOnly {
			fmt.Fprintf(&b, "--   %s: %s.\n", o.Signature, o.Reason)
		}
	}
	b.WriteString("-- Relations.\n")
	for _, t := range inv.Tables {
		if len(t.Privileges) == 0 {
			fmt.Fprintf(&b, "-- no access: public.%s\n", t.Name)
			continue
		}
		fmt.Fprintf(&b, "GRANT %s ON TABLE public.%s TO :\"%s\";\n", strings.Join(t.Privileges, ", "), t.Name, RoleVariable)
	}
	b.WriteString("-- Sequences used by the inserts above.\n")
	for _, s := range inv.Sequences {
		fmt.Fprintf(&b, "GRANT USAGE ON SEQUENCE public.%s TO :\"%s\";\n", s, RoleVariable)
	}
	b.WriteString("-- Functions the runtime calls that PUBLIC cannot execute.\n")
	if len(inv.Functions) == 0 {
		b.WriteString("-- none: every function the runtime calls is executable by PUBLIC.\n")
	}
	for _, f := range inv.Functions {
		fmt.Fprintf(&b, "GRANT EXECUTE ON FUNCTION public.%s TO :\"%s\";\n", f, RoleVariable)
		allowedDefiner = append(allowedDefiner, "'"+f+"'")
	}
	fmt.Fprintf(&b, `-- Safety net until this script is re-run after a migration: objects the
-- owner creates later get ordinary DML (never TRUNCATE, REFERENCES, TRIGGER
-- or MAINTAIN); re-running converges them to the derived inventory (EDR-364).
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO :"%[1]s";
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT USAGE ON SEQUENCES TO :"%[1]s";

DO $runtime_verify$
DECLARE
  role_name text := pg_catalog.current_setting('abastevo.runtime_role');
  bad text;
BEGIN
  IF EXISTS (SELECT 1 FROM pg_catalog.pg_roles WHERE rolname = role_name
      AND (rolsuper OR rolbypassrls OR rolcreaterole OR rolcreatedb OR rolreplication OR rolinherit OR NOT rolcanlogin)) THEN
    RAISE EXCEPTION 'runtime role attributes are not ordinary';
  END IF;
  IF EXISTS (SELECT 1 FROM pg_catalog.pg_roles r WHERE pg_catalog.pg_has_role(role_name, r.oid, 'MEMBER')
      AND (r.rolsuper OR r.rolbypassrls OR r.rolcreaterole))
     OR EXISTS (SELECT 1 FROM pg_catalog.pg_class c WHERE c.relrowsecurity AND pg_catalog.pg_has_role(role_name, c.relowner, 'MEMBER')) THEN
    RAISE EXCEPTION 'runtime role would be refused by the organization role guard';
  END IF;
  SELECT pg_catalog.string_agg(c.relname, ', ' ORDER BY c.relname) INTO bad
    FROM pg_catalog.pg_class c JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace
   WHERE n.nspname = 'public' AND c.relkind IN ('r','p','v','m')
     AND (pg_catalog.has_table_privilege(role_name, c.oid, 'TRUNCATE')
       OR pg_catalog.has_table_privilege(role_name, c.oid, 'REFERENCES')
       OR pg_catalog.has_table_privilege(role_name, c.oid, 'TRIGGER')
       OR CASE WHEN pg_catalog.current_setting('server_version_num')::int >= 170000
               THEN pg_catalog.has_table_privilege(role_name, c.oid, 'MAINTAIN') ELSE false END);
  IF bad IS NOT NULL THEN
    RAISE EXCEPTION 'runtime role holds TRUNCATE, REFERENCES, TRIGGER or MAINTAIN on %%', bad;
  END IF;
  IF pg_catalog.has_schema_privilege(role_name, 'public', 'CREATE')
     OR pg_catalog.has_database_privilege(role_name, pg_catalog.current_database(), 'CREATE') THEN
    RAISE EXCEPTION 'runtime role can create objects; revoke CREATE on schema public and the database from PUBLIC first';
  END IF;
  SELECT pg_catalog.string_agg(p.oid::regprocedure::text, ', ' ORDER BY 1) INTO bad
    FROM pg_catalog.pg_proc p JOIN pg_catalog.pg_namespace n ON n.oid = p.pronamespace
   WHERE n.nspname = 'public' AND p.prosecdef
     AND pg_catalog.has_function_privilege(role_name, p.oid, 'EXECUTE')
     AND p.oid::regprocedure::text <> ALL (ARRAY[%[2]s]::text[]);
  IF bad IS NOT NULL THEN
    RAISE EXCEPTION 'runtime role can execute SECURITY DEFINER functions: %%', bad;
  END IF;
END
$runtime_verify$;

COMMIT;
`, RoleVariable, strings.Join(allowedDefiner, ", "))
	return b.Bytes()
}

// ForRole substitutes the psql role variable so a Go test can apply the
// script through an ordinary connection exactly as psql would.
func ForRole(script []byte, role string) (string, error) {
	if !roleName.MatchString(role) {
		return "", ErrInvalidRole
	}
	text := strings.ReplaceAll(string(script), ":'"+RoleVariable+"'", "'"+role+"'")
	text = strings.ReplaceAll(text, `:"`+RoleVariable+`"`, `"`+role+`"`)
	if strings.Contains(text, ":'") || strings.Contains(text, `:"`) {
		return "", errors.New("runtimegrants: unresolved psql variable")
	}
	return text, nil
}
