// DRV-02 freezes manual expectations before earnings/time runtime exists.
// This reference consumer belongs only to tests. Future phases must execute the
// same rows through their real domain/application paths, not cite this as UI proof.
func TestDriverManualReferenceVectors(t *testing.T) {
	f, err := os.Open("../../../../contracts/testdata/driver-suite/driver-manual-reference-v1.psv")
	if err != nil {
		t.Fatal(err)
	}
	defer f.Close()
	plannedBytes, err := os.ReadFile("../../../../contracts/testdata/driver-suite/planned-financial-v1.json")
	if err != nil {
		t.Fatal(err)
	}
	var planned struct {
		Vectors []struct {
			ID       string         `json:"id"`
			Expected map[string]any `json:"expected"`
		} `json:"vectors"`
	}
	decoder := json.NewDecoder(strings.NewReader(string(plannedBytes)))
	decoder.UseNumber()
	if err := decoder.Decode(&planned); err != nil {
		t.Fatal(err)
	}
	baseline := map[string]map[string]any{}
	for _, v := range planned.Vectors {
		baseline[v.ID] = v.Expected
	}
	// Aliases only; expectations stay in the frozen fixtures, not generated by
	// this evaluator. These eight planning rows must all be encountered.
	aliases := map[string]map[string]string{
		"DRV-V06": {"earned": "earned_net_centavos"},
		"DRV-V07": {"earned": "earned_net_centavos", "gross": "gross_centavos", "unknown": "unknown"},
		"DRV-V08": {"earned": "earned_net_centavos", "received": "bank_received_centavos"},
		"DRV-V09": {"result": "recorded_result_centavos", "per_km": "result_centavos_per_km_rational", "per_hour": "result_centavos_per_hour_rational"},
		"DRV-V10": {"recorded": "recorded_result_centavos_unchanged", "modeled": "modeled_result_centavos", "per_km": "modeled_centavos_per_km_rational", "per_hour": "modeled_centavos_per_hour_rational"},
		"DRV-V11": {"union": "union_seconds", "summed": "not_summed_seconds"},
		"DRV-V17": {"per_km": "income_per_km", "per_hour": "income_per_hour", "unknown": "unknown"},
		"DRV-V20": {"result": "complete_operating_result_centavos", "unknown": "unknown"},
	}
	seen := map[string]bool{}
	sc := bufio.NewScanner(f)
	if !sc.Scan() || sc.Text() != "id|operation|args|expected" {
		t.Fatal("invalid manual reference header")
	}
	for sc.Scan() {
		cols := strings.Split(sc.Text(), "|")
		if len(cols) != 4 || cols[0] == "" || seen[cols[0]] {
			t.Fatalf("invalid or duplicate reference row %q", sc.Text())
		}
		id := cols[0]
		seen[id] = true
		t.Run(id, func(t *testing.T) {
			args, want := manualReferenceKV(t, cols[2]), manualReferenceKV(t, cols[3])
			if got := manualReferenceCompute(t, cols[1], args); !reflect.DeepEqual(want, got) {
				t.Fatalf("got %v want %v", got, want)
			}
			for key, plannedKey := range aliases[id] {
				v, exists := baseline[id][plannedKey]
				if !exists {
					t.Fatalf("missing planning field %s.%s", id, plannedKey)
				}
				text := fmt.Sprint(v)
				if v == nil {
					text = "null"
				} else if parts, ok := v.([]any); ok {
					s := make([]string, len(parts))
					for i, p := range parts {
						s[i] = fmt.Sprint(p)
					}
					text = strings.Join(s, ",")
				}
				if want[key] != text {
					t.Fatalf("manual expectation differs from frozen planning %s: %q != %q", plannedKey, want[key], text)
				}
			}
		})
	}
	if sc.Err() != nil || len(seen) != 15 {
		t.Fatalf("rows=%d err=%v", len(seen), sc.Err())
	}
	for id := range aliases {
		if !seen[id] {
			t.Fatalf("missing planned reference %s", id)
		}
	}
}

func manualReferenceKV(t *testing.T, raw string) map[string]string {
	t.Helper()
	out := map[string]string{}
	for _, pair := range strings.Split(raw, ";") {
		k, v, ok := strings.Cut(pair, "=")
		if _, duplicate := out[k]; !ok || k == "" || duplicate {
			t.Fatalf("invalid reference pair %q", pair)
		}
		out[k] = v
	}
	return out
}

func manualReferenceCompute(t *testing.T, op string, a map[string]string) map[string]string {
	t.Helper()
	number := func(s string) int64 {
		v, err := strconv.ParseInt(s, 10, 64)
		if err != nil {
			t.Fatal(err)
		}
		return v
	}
	sum := func(s string) int64 {
		var n int64
		for _, part := range strings.Split(s, ",") {
			n += number(part)
		}
		return n
	}
	text := func(n int64) string { return strconv.FormatInt(n, 10) }
	ratios := func(amount int64) map[string]string {
		out := map[string]string{"unknown": ""}
		var reasons []string
		for _, ratio := range []struct {
			input, output, reason string
			scale                 int64
		}{{"distance", "per_km", "distance", 1000}, {"seconds", "per_hour", "time", 3600}} {
			v := a[ratio.input]
			switch {
			case v == "null":
				out[ratio.output] = "null"
				reasons = append(reasons, ratio.reason+"-missing")
			case number(v) <= 0:
				out[ratio.output] = "null"
				reasons = append(reasons, ratio.reason+"-nonpositive")
			default:
				r := new(big.Rat).Mul(big.NewRat(amount, number(v)), big.NewRat(ratio.scale, 1))
				out[ratio.output] = r.RatString()
			}
		}
		out["unknown"] = strings.Join(reasons, ",")
		return out
	}
	switch op {
	case "DETAILED":
		return map[string]string{"earned": text(number(a["gross"]) - number(a["fees"]) + number(a["tips"]) + number(a["bonus"]) - number(a["refund"]))}
	case "NET":
		return map[string]string{"earned": text(number(a["inclusive"])), "gross": "null", "fees": "null", "unknown": "gross-and-fee-components-unknown"}
	case "PAYOUT":
		return map[string]string{"earned": text(number(a["earned"])), "received": text(number(a["payout"]))}
	case "RESULT":
		if a["complete"] != "1" || a["costs"] == "null" {
			return map[string]string{"result": "null", "per_km": "null", "per_hour": "null", "unknown": "cost-coverage-incomplete"}
		}
		n := number(a["earned"]) - sum(a["costs"])
		out := ratios(n)
		out["result"] = text(n)
		return out
	case "MODEL":
		n := number(a["recorded"]) - sum(a["estimates"])
		out := ratios(n)
		out["recorded"], out["modeled"] = a["recorded"], text(n)
		return out
	case "RATIOS":
		return ratios(number(a["amount"]))
	case "UNION":
		var spans [][2]int64
		var summed int64
		for _, span := range strings.Split(a["intervals"], ",") {
			p := strings.Split(span, ":")
			if len(p) != 2 {
				t.Fatal("invalid reference interval")
			}
			start, end := number(p[0]), number(p[1])
			if start < 0 || end <= start {
				t.Fatal("invalid reference interval bounds")
			}
			spans = append(spans, [2]int64{start, end})
			summed += end - start
		}
		sort.Slice(spans, func(i, j int) bool { return spans[i][0] < spans[j][0] })
		start, end := spans[0][0], spans[0][1]
		var union int64
		for _, span := range spans[1:] {
			if span[0] > end {
				union += end - start
				start, end = span[0], span[1]
			} else if span[1] > end {
				end = span[1]
			}
		}
		return map[string]string{"union": text(union + end - start), "summed": text(summed)}
	default:
		t.Fatalf("unknown reference operation %q", op)
		return nil
	}
}
