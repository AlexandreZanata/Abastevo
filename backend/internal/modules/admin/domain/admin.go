// Package domain owns administrative authentication rules: key shape and
// matching, reason validation and session timing. It performs no I/O and
// never stores or logs key, session or CSRF material.
package domain

import (
	"crypto/sha256"
	"crypto/subtle"
	"encoding/base64"
	"encoding/hex"
	"errors"
	"strings"
	"time"
)

const (
	KeyPrefix    = "abv_admin_"
	KeyRandom    = 32
	KeyBase64Len = 43
	KeyLength    = len(KeyPrefix) + KeyBase64Len

	SessionTokenBytes = 32
	SessionSaltBytes  = 16

	IdleTimeout      = 30 * time.Minute
	AbsoluteLifetime = 8 * time.Hour

	MinReasonRunes = 10
	MaxReasonRunes = 500
)

var (
	ErrInvalid      = errors.New("admin: invalid input")
	ErrDenied       = errors.New("admin: denied")
	ErrRateLimited  = errors.New("admin: rate limited")
	ErrUnauthorized = errors.New("admin: session required")
	ErrCSRF         = errors.New("admin: csrf denied")
	ErrConflict     = errors.New("admin: conflict")
	ErrNotFound     = errors.New("admin: not found")
	ErrUnavailable  = errors.New("admin: unavailable")
)

// RateLimitedError carries the bounded retry delay without any credential.
type RateLimitedError struct {
	RetryAfter time.Duration
}

func (e *RateLimitedError) Error() string { return "admin: rate limited" }
func (e *RateLimitedError) Unwrap() error { return ErrRateLimited }

// ConfiguredKey is one accepted key hash plus its non-secret fingerprint.
type ConfiguredKey struct {
	Hash        string
	Fingerprint string
}

// ValidKey reports the exact key format generated by ops admin keygen.
func ValidKey(raw string) bool {
	if len(raw) != KeyLength || !strings.HasPrefix(raw, KeyPrefix) {
		return false
	}
	decoded, err := base64.RawURLEncoding.DecodeString(raw[len(KeyPrefix):])
	return err == nil && len(decoded) == KeyRandom
}

// HashKey returns the lowercase hex SHA-256 of the full key string.
func HashKey(raw string) string {
	sum := sha256.Sum256([]byte(raw))
	return hex.EncodeToString(sum[:])
}

// ValidHash accepts exactly the configured lowercase hex SHA-256 shape.
func ValidHash(raw string) bool {
	if len(raw) != 64 || strings.ToLower(raw) != raw {
		return false
	}
	_, err := hex.DecodeString(raw)
	return err == nil
}

// Fingerprint is the stable first 12 hex characters stored with a session.
func Fingerprint(hash string) string {
	if len(hash) < 12 {
		return ""
	}
	return hash[:12]
}

// MatchKey compares the presented key hash against every configured hash in
// constant time. The returned fingerprint is safe to persist; the key is not.
func MatchKey(presentedHash string, keys []ConfiguredKey) (ConfiguredKey, bool) {
	var matched ConfiguredKey
	found := false
	for _, key := range keys {
		if subtle.ConstantTimeCompare([]byte(presentedHash), []byte(key.Hash)) == 1 {
			matched = key
			found = true
		}
	}
	return matched, found
}

// FingerprintAllowed reports whether a session's fingerprint still matches a
// currently configured hash (ADM-07 rotation).
func FingerprintAllowed(fingerprint string, keys []ConfiguredKey) bool {
	for _, key := range keys {
		if subtle.ConstantTimeCompare([]byte(fingerprint), []byte(key.Fingerprint)) == 1 {
			return true
		}
	}
	return false
}

// ValidReason accepts 10–500 Unicode characters after trimming.
func ValidReason(raw string) bool {
	runes := []rune(strings.TrimSpace(raw))
	return len(runes) >= MinReasonRunes && len(runes) <= MaxReasonRunes
}

// ValidUUID is the server-side canonical UUID check used for idempotency and
// path identifiers.
func ValidUUID(raw string) bool {
	if len(raw) != 36 || raw[8] != '-' || raw[13] != '-' || raw[18] != '-' || raw[23] != '-' || strings.ToLower(raw) != raw {
		return false
	}
	_, err := hex.DecodeString(strings.ReplaceAll(raw, "-", ""))
	return err == nil
}

// ValidToken accepts exactly 32 random bytes encoded base64url without
// padding.
func ValidToken(raw string) bool {
	decoded, err := base64.RawURLEncoding.DecodeString(raw)
	return err == nil && len(decoded) == SessionTokenBytes
}

// NewToken returns a fresh base64url token.
func NewToken(bytes []byte) string { return base64.RawURLEncoding.EncodeToString(bytes) }

// SaltedHash binds one secret to a per-record salt. Hex output keeps the
// database column shape explicit.
func SaltedHash(salt, secret string) string {
	sum := sha256.Sum256([]byte(salt + "\x00" + secret))
	return hex.EncodeToString(sum[:])
}

// LookupDigest is the deterministic digest used only to find one session row
// before comparing its salted hash. It is not the stored session verifier.
func LookupDigest(raw string) string {
	sum := sha256.Sum256([]byte("admin-session-lookup\x00" + raw))
	return hex.EncodeToString(sum[:])
}

// SessionLive applies idle and absolute timeouts (ADM-05).
func SessionLive(created, lastSeen, expires, now time.Time) bool {
	return !now.Before(created) &&
		now.Before(expires) &&
		now.Sub(lastSeen) < IdleTimeout
}
